#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
parallel.py — 几百个小核并行, 能解决顶级难题吗?
==================================================
两个定律决定答案 (都可精确计算):

① Amdahl 定律: 并行加速的上限
   任务中必须【串行】的比例 f
   加速上限 = 1/f   (与核数无关!)

② 错误累积: 序列任务的并行需求是【指数级】
   深度 L 的任务, 每步成功率 p
   单核成功 = p^L
   需要 K 个并行才能把成功率提到 0.5 → K ≈ ln2 / p^L
   → L 越大, K 指数爆炸

本实验: 对三类真实任务算这两个数字
"""
import numpy as np, time

t0 = time.time()

print('=' * 76)
print('定律①: Amdahl — 串行比例决定并行上限')
print('=' * 76)
print()
print('  %-28s %-14s %-16s %s' % ('任务类型', '串行比例 f', '加速上限 1/f', '即使有无限核'))
print('  ' + '-' * 72)
rows = [
    ('纯广度搜索(lemma遍历)', 0.02, '50x'),
    ('多分支证明(部分独立)', 0.15, '6.7x'),
    ('长链推理(每步依赖前步)', 0.60, '1.7x'),
    ('单点关键洞察', 0.98, '1.02x'),
]
for nm, f, cap in rows:
    print('  %-28s %-14.2f %-16s %s' % (nm, f, cap,
          '✅ 并行有效' if f < 0.2 else ('⚠️ 有限' if f < 0.5 else '❌ 几乎无效')))

print()
print('=' * 76)
print('定律②: 错误累积 — 深度任务的并行需求')
print('=' * 76)
print()
print('  假设每步成功率 p=0.9 (已经很好了), 看要多少并行核才能达到 50%')
print()
print('  %-10s %-16s %-20s %s' % ('链长L', '单链成功率', '所需并行核数 K', '可行?'))
print('  ' + '-' * 70)
for L in [3, 5, 10, 20, 40, 80]:
    p = 0.9
    pL = p ** L
    K = np.log(0.5) / np.log(max(1 - pL, 1e-300))
    tag = ('✅ 可行' if K < 1000 else
           ('⚠️ 勉强' if K < 1e6 else
            ('❌ 不可能' if K < 1e30 else '❌❌ 天文数字')))
    print('  %-10d %-16.2e %-20.1f %s' % (L, pL, K, tag))

print()
print('=' * 76)
print('对照: 广度搜索 (并行真的有线性加速)')
print('=' * 76)
print()
print('  %-16s %-16s %-16s %s' % ('搜索空间', '解的密度', '单核步数', '100核步数'))
print('  ' + '-' * 68)
for space, dens in [(1e6, 1e-3), (1e9, 1e-6), (1e12, 1e-9), (1e18, 1e-12)]:
    print('  %-16.0e %-16.0e %-16.0e %.0e' % (space, dens, 1/dens, 1/dens/100))

print()
print('=' * 76)
print('★ 核心结论')
print('=' * 76)
print('  ✅ 并行有效: 广度型 (lemma探索/枚举/验证/多种尝试)')
print('     → 线性加速, 100核 = 100倍')
print()
print('  ❌ 并行无效: 深度型 (长链推理/关键洞察)')
print('     → 链长 >20 步时, 需要百万~天文数字级并行')
print()

# ---------- 现实对照: 顶尖数学任务的构成 ----------
print('=' * 76)
print('现实: 一个顶尖数学任务的时间都花在哪?')
print('=' * 76)
print()
print('  %-30s %-12s %-12s %s' % ('阶段', '占比', '任务类型', '并行的作用'))
print('  ' + '-' * 72)
stages = [
    ('① 理解问题/形式化', '5%', '浅', '有限'),
    ('② 枚举可能方向(lemma)', '30%', '广度', '★ 有效'),
    ('③ 证明每条lemma', '35%', '深度(链长5-15)', '有限'),
    ('④ 关键洞察/换思路', '25%', '单点(不可拆)', '❌ 无效'),
    ('⑤ 验证/写论文', '5%', '浅+广度', '★ 有效'),
]
for s in stages:
    print('  %-30s %-12s %-12s %s' % s)
print()

print('  可并行部分: ②+⑤ ≈ 35%   → Amdahl 上限 ≈ 2.9x')
print('  不可并行部分: ④ ≈ 25%    → 决定成败, 而且【完全不能并行】')
print()
print('  用时 %.2fs' % (time.time() - t0))
