# ============ 实验1: 只组合不命名 = 有限 ============
print("\n【实验1】只有「组合」, 没有「命名」—— 就是有限的")
W = 20
print(f"  原子数固定 = {W} 个")
print(f"  {'最大深度':<12}{'能表达的东西数':<26}{'性质'}")
print("  "+"-"*62)
for d in [1,2,3,5,10]:
    print(f"  {d:<12}{W**d:<26.3e}{'有限' if d<10 else '有限(但天文)'}")
print("  ★ 无论深度多大, 都是【有限】—— 这就是你说的那个坎")

# ============ 实验2: 加上「命名」—— 原子自己长大 ============
print("\n【实验2】每层把组合结果【命名】成新原子")
atoms = W
print(f"  {'层':<6}{'可用原子数':<28}{'新增组合':<26}{'性质'}")
print("  "+"-"*76)
for d in range(1,6):
    combo = atoms*atoms
    atoms = atoms + combo          # 命名: 组合结果 -> 新原子
    print(f"  {d:<6}{atoms:<28.3e}{combo:<26.3e}{'★ 爆炸' if d>1 else ''}")
print("  ★ 关键: 原子数【每层平方】-> 而「命名」这一步是人给的? 不, 是自动的")
print("  ★ 一旦能自动命名, 深度就【不受限】了 -> 从有限跳到无限")

# ============ 实验3: 层级跃迁 (有限定义, 能力无限上升) ============
print("\n【实验3】用「重复上一层」定义新函数 —— 一行定义, 能力爆炸")
def rep(f, n, x):
    for _ in range(max(n,0)):
        x = f(x)
        if x > 10**300: return x
    return x
s = lambda x: x+1                       # 第0层: 后继
levels = [s]
names = ['后继 n+1']
for k in range(1,4):
    prev = levels[-1]
    # 第k层 = 把上一层重复 n 次  <- 【一行定义】
    levels.append(lambda x, p=prev: rep(p, x, x))
print(f"  {'层级':<10}{'定义':<26}{'输入10得到'}")
print("  "+"-"*66)
print(f"  {'第0层':<10}{'后继 n+1':<26}{10+1}")
v1 = rep(s, 10, 10)
print(f"  {'第1层':<10}{'重复后继 10 次':<26}{v1}")
v2 = rep(lambda x: rep(s, x, x), 10, 10)
print(f"  {'第2层':<10}{'重复第1层 10 次':<26}{v2}")
v3 = rep(lambda x: rep(lambda y: rep(s, y, y), x, x), 10, 10)
print(f"  {'第3层':<10}{'重复第2层 10 次':<26}{v3 if v3<10**300 else '>10^300 (天文)'}")
print("  ★ 每一层只是【一行定义】(重复上一层), 但能力【指数跃迁】")
print("  ★ 而且「重复上一层」这个动作本身, 就是【命名】: 上一层变成了可调用的原子")

