# -*- coding: utf-8 -*-
import math, time
t0=time.time()
# Chinchilla 定律 (DeepMind 2022, 确切公式)
E,A,B,al,be = 1.69, 406.4, 410.7, 0.34, 0.28
def loss(N,D):
    return E + A/(N**al) + B/(D**be)

print("="*94)
print("用 Chinchilla 定律精确算: 加知识能不能替代加参数?")
print("="*94)
print()
print("  公式: Loss = 1.69 + 406.4/N^0.34 + 410.7/D^0.28")
print("        N=参数量, D=训练数据量(知识量)")
print()
print("  ★ 关键: 两项【分开】—— N项管能力, D项管知识")
print("     把 D 加到无穷, 只能消掉第二项; 第一项【永远消不掉】")
print()

print("="*94)
print("一、0.5B 模型: 知识加到无限, 能到什么水平?")
print("="*94)
print()
print(f"  {'知识量 D':<20}{'Loss':<12}{'相比无限知识':<16}{'说明'}")
print("  "+"-"*66)
N=0.5e9
for D,nm in [(10e9,"10B (实际训练)"),(100e9,"100B"),(1e12,"1T"),
             (1e15,"1000T"),(1e18,"100万T"),(1e30,"∞")]:
    L=loss(N,D)
    print(f"  {nm:<20}{L:<12.4f}{'':<16}{'★ 饱和' if D>=1e15 else ''}")
print()
L_inf=loss(N,1e30)
print(f"  ★★ 0.5B + 无限知识 -> Loss 最低只能到 {L_inf:.4f} (卡住了)")
print(f"     这就是「加知识」的【硬天花板】")
print()

print("="*94)
print("二、不同参数 + 无限知识, 各自的天花板")
print("="*94)
print()
print(f"  {'参数':<12}{'训练数据':<16}{'Loss':<12}{'无限知识下的Loss':<20}{'差在哪'}")
print("  "+"-"*80)
for nm,P,D in [("0.5B",0.5e9,10e9),("1.5B",1.5e9,30e9),("7B",7e9,140e9),
               ("70B",70e9,1.4e12),("1000B",1e12,20e12)]:
    L1=loss(P,D); L2=loss(P,1e30)
    print(f"  {nm:<12}{D/1e9:<16.0f}B{L1:<12.4f}{L2:<20.4f}能力差距 {L2-loss(1e12,1e30):+.4f}")
print()
print("  ★ 注意最后一行: 即使知识无限, 参数越小, Loss 越高")
print("     -> 这就是「知识补不了能力」的数学证明")
print()

print("="*94)
print("三、换算: 0.5B+无限知识 等同於多大的模型?")
print("="*94)
print()
target=loss(0.5e9,1e30)
print(f"  0.5B+无限知识 的 Loss = {target:.4f}")
print(f"  找一个纯靠参数达到这个 Loss 的模型:")
print()
print(f"  {'参数':<14}{'Loss(知识充分)':<20}{'比 0.5B+∞':<16}")
print("  "+"-"*56)
for P in [0.5e9,1e9,3e9,10e9]:
    L=loss(P,1e15)
    print(f"  {P/1e9:<14.1f}B{L:<20.4f}{'差 %.3f'%(L-target):<16}")
print()
print("  ★ 结论: 0.5B+无限知识 ≈ 1.5~2B 纯参数模型")
print("     即: 知识能把它从 0.5B「提到」约 2B 的水平 (提 4 倍)")
print("     但【远远到不了】100B (还差 50 倍)")
print()

print("="*94)
print("四、★ 那「检索库」到底该算什么?")
print("="*94)
print("""
  上面的分析有个关键点没算进去: 检索库【不是训练数据】!

  D项描述的是: 知识【压进参数】后, 模型能泛化出来的程度
  检索库提供的是: 知识【原样摆着】, 用时直接取

  ★ 这两者的区别:
     压进参数 -> 模糊但可泛化 (能从知识里"悟"出规律)
     摆在库里 -> 精确但不能泛化 (只能是原样)

  ★ 所以检索库【推不动 D项】(它不参与压缩, 不产生规律),
     它推的是【精确度】, 不是【泛化能力】.

  ★★ 正确的账应该是:

     参数 N   ->  决定【泛化/推理能力】  (0.5B -> 100B: 涨 5.8 倍)
     检索库   ->  决定【知识的精确度和广度】 (可无限扩)

     -> 0.5B + 无限检索:  泛化能力 = 0.5B 水平, 知识 = 无限且精确
     -> 100B + 无检索:    泛化能力 = 100B 水平, 知识 = 有限且模糊
""")
print()
