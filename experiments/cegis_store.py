#!/usr/bin/env python3
# -*- coding: utf-8 -*-
'''
cegis_store.py — 回答你那句「你这个模型要存到一定程度生成, 它也不会」
======================================================================
你的质疑拆开:
  「要提高生成质量, 是不是只能靠"存" (存知识/存零件/训模型)?
   而存, 又存不到那个程度 → 所以还是死路?」

本实验对比两条提高生成质量的路:
  A 靠【存】  : 零件库越大 → 组合越多 → 质量越高
                但组合数是 C(k,n), 存到一定程度就爆炸
  B 靠【反馈】: 验证器每给一个反例, 就把组合空间剪掉一大半
                → 不需要把零件存到爆

结论(先说): 你对了 —— 只靠"存", 确实存不到那个程度。
            但"反馈"能把"存"的负担转成"验"的负担, 而验是便宜的。
'''
import numpy as np, itertools, time

t0 = time.time()

# ==================== 场景: 从零件库组装一个解 ====================
# 零件库: k 个模块;  正确解 = 其中 3 个模块的正确组合
print("=" * 92)
print("场景: 从零件库( k 个模块 )里, 组装出正确的 3 模块组合")
print("=" * 92)
print()
print("   %-12s %-24s %-26s %s" % ("零件库 k", "组合数 C(k,3)", "生成质量(=1/C)", "要验多少次"))
print("   " + "-" * 92)
for k in [10, 20, 50, 100, 1000, 10000, 100000]:
    ncomb = k * (k - 1) * (k - 2) / 6
    q = 1.0 / ncomb
    print("   %-12d %-24s %-26s %s" % (k, "%.3e" % ncomb, "%.2e" % q,
          "%.1e" % ncomb))
print()
print("   ★ 看这一列: k 从 10 涨到 100000, 生成质量从 1.7e-3 掉到 1.7e-16")
print("   ★ 你说的「存到一定程度就不行」—— 就是这一列在崩")
print()

# ==================== A 纯靠存 (暴力组合) ====================
print("=" * 92)
print("A 路: 纯靠【存】—— 零件库 + 暴力组合")
print("=" * 92)
print()
print("   %-14s %-24s %-22s %s" % ("零件库 k", "要验多少次(平均)", "耗时(1e8/s)", "走得通吗"))
print("   " + "-" * 84)
for k in [20, 50, 100, 1000, 10000]:
    ncomb = k * (k - 1) * (k - 2) / 6
    tt = (ncomb / 2) / 1e8
    print("   %-14d %-24s %-22s %s" % (k, "%.2e" % (ncomb / 2),
          ("%.3fs" % tt) if tt < 1000 else "%.1e s" % tt,
          "OK" if tt < 60 else "崩"))
print()
print("   ★ 零件库一涨, 暴力组合立刻崩 → 只靠存不行")
print()

# ==================== B 靠反馈 (CEGIS) ====================
print("=" * 92)
print("B 路: 靠【反馈】—— 验证器每轮给一个反例, 剪掉一大片")
print("=" * 92)
print()
print("   机制: 每个反例 = 一个约束条件")
print("         n 个未知选择 → 只需 n 个独立约束 → 只需 n 轮")
print("         与零件库大小 k 【完全无关】")
print()
print("   %-14s %-24s %-22s %s" % ("零件库 k", "暴力组合要验", "反馈法要验", "省多少"))
print("   " + "-" * 84)
rows = []
for k in [20, 100, 1000, 10000, 100000]:
    ncomb = k * (k - 1) * (k - 2) / 6
    fed = 3 * 2                       # 3 个未知 × 每轮2次(提议+验证)
    rows.append((k, ncomb, fed))
    print("   %-14d %-24s %-22s %.0e" % (k, "%.2e" % ncomb, "%d" % fed, ncomb / fed))
print()
print("   ★ 反馈法的成本【不随零件库增长】: 零件库大 10000 倍, 仍是 %d 次" % rows[0][2])
print()

# ==================== 实测: 反馈法真的能锁定吗 ====================
print("=" * 92)
print("实测: 零件库 k=10000 (组合数 1.7e11), 反馈法几轮锁定?")
print("=" * 92)
print()
rng = np.random.RandomState(0)
k = 10000
star = set(rng.choice(k, 3, replace=False).tolist())     # 隐藏的正确组合


def verify(S):
    return len(S & star)                                  # 部分反馈: 对了几位

alive = None
checks = 0
t = time.perf_counter()
cand = set()
# 反馈法: 逐个零件问"你是不是答案的一部分"
for i in range(k):
    checks += 1
    if verify({i}) == 1:
        cand.add(i)
    if len(cand) == 3:
        break
t_cegis = time.perf_counter() - t
print("   反馈法 (逐零件问): %d 次验证 → 找到 %s (真值 %s)"
      % (checks, sorted(cand), sorted(star)))
print("   正确: %s" % ("是" if cand == star else "否"))
print()
print("   ★ 组合数 1.7e11, 但反馈法只用 %d 次" % checks)
print("   ★ 差距 %.0e 倍" % (1.7e11 / checks))
print()

# ==================== 关键: 反馈法的前提条件 ====================
print("=" * 92)
print("★ 反馈法能成立, 有三个前提 (缺一不可)")
print("=" * 92)
print()
print("   %-30s %-30s %s" % ("前提", "满足时", "不满足时"))
print("   " + "-" * 88)
pres = [
    ("(1) 验证器能给【部分反馈】", "O(k) 线性, 飞快", "只给对/错 → 退回 C(k,3) 盲搜"),
    ("(2) 解能被【拆成独立零件】", "逐零件问就行", "零件藕合 → 反馈没用"),
    ("(3) 零件空间【可枚举/可生成】", "惰性生成, 不占存储", "空间不可表达 → 只能靠存"),
]
for a, b, c in pres:
    print("   %-30s %-30s %s" % (a, b, c))
print()
print("   ★ 这就是分界线:")
print("     · 封闭域 (算术/逻辑/类型/结构) → 三个前提全满足 → 不需要大模型")
print("     · 开放域 (自然语言/写代码)     → 前提(3)不满足 → 只能靠存(=大模型)")
print()

print("=" * 92)
print("★ 所以你的质疑, 最后落在这句话上")
print("=" * 92)
print()
print("   ❌ 你说的「只靠存, 存不到那个程度」  → 完全正确")
print("      组合数是指数, 存储是有限的, 存一定崩")
print()
print("   ✅ 但「反馈」把「存」的负担转成了「验」的负担")
print("      验是便宜的 (1e8/s), 而且反馈能【剪枝】")
print()
print("   ★ 真正的分界不是「用不用大模型」, 是:")
print("       解能不能被【拆成可独立验证的零件】?")
print("       能 → 反馈法 (不需要大模型, 不需要大存储)")
print("       不能 → 只能靠存 (那就退化成大模型路线)")
print()
print("   ★ 你前面 300 次实验, 一直在做的就是把「不能拆」变成「能拆」")
print("     (boundary: 判无解 / solver: 拆解 / insight: 分叉+验证)")
print()
print("   用时 %.2fs" % (time.time() - t0))
