# ============ 实验: 排版任务 (经典塔尖任务) ============
print("="*94)
print("二、真跑: 把「写一首诗」这个塔尖任务, 搬成腰部任务")
print("="*94)
print()
# 设定: 中文五言, 有韵脚约束
RHYME={'a':['花','家','沙','涯','华','涯'],'b':['风','空','中','红','峰','同'],
       'c':['水','里','起','子','已'],'d':['山','间','川','天','年']}
WORDS=['春风','明月','流水','白云','青山','孤舟','寒江','野径',
       '花开','叶落','鸟鸣','钟响','夜静','秋深','路远','心闲']
print("  任务: 写一句五言诗 (春/风/花/月), 末字要押韵")
print()
print("  【塔尖做法】'写一首好诗' —— 无法机械化 (要品味)")
print("  【腰部做法】把'好'拆成【可检验的条件】:")
print("     条件1: 5个字")
print("     条件2: 末字在韵脚表里")
print("     条件3: 不含重复字")
print("     条件4: 词都来自词典")
print()

import itertools
def is_valid(s):
    if len(s)!=5: return False
    if s[-1] not in RHYME['a']+RHYME['b']+RHYME['c']+RHYME['d']: return False
    if len(set(s))!=5: return False
    return True

# 构造: 从词典里组合
cands=[]
for w1,w2 in itertools.product(WORDS,WORDS):
    for last in RHYME['a']:
        s=w1+w2+last          # 2+2+1 = 5字
        cands.append(s)
print(f"  机械生成候选: {len(cands)} 个")
valid=[s for s in cands if is_valid(s)]
print(f"  验证器筛出的合格品: {len(valid)} 个")
print()
print("  合格品例子:")
for s in valid[:6]:
    print(f"     {s}   (末字押韵: {s[-1]})")
print()
print(f"  ★ 全程没有「品味」参与 —— 只有【生成 + 验证】")
print()

# ============ 关键: 转换的质量取决于什么 ============
print("="*94)
print("三、★ 转换的质量, 取决于「判定标准写得够不够好」")
print("="*94)
print()
print(f"  {'判定标准的严格度':<26}{'合格品数':<14}{'质量'}")
print("  "+"-"*62)
tests=[
 ("只要5个字",              lambda s: len(s)==5, []),
 ("+末字押韵",              lambda s: len(s)==5 and s[-1] in RHYME['a'], []),
 ("+不重复字",              lambda s: len(s)==5 and s[-1] in RHYME['a'] and len(set(s))==5, []),
 ("+词来自词典",            lambda s: len(s)==5 and s[-1] in RHYME['a'] and len(set(s))==5 and (s[:2] in WORDS and s[2:4] in WORDS), []),
]
for nm,fn,_ in tests:
    n=sum(1 for s in cands if fn(s))
    q="宽松" if n>1000 else ("适中" if n>50 else "严格")
    print(f"  {nm:<26}{n:<14}{q}")
print()
print("  ★ 判定标准越严, 合格品越少越精 -> 但生成要越强 (否则筛光了)")
print("  ★ 这就是这台机器的【调节旋钮】")
print()

