print("""
  第1步: 标准挖掘
     从人类示例里, 反推"他为什么选这个"
     -> 得到一组可检验条件 (哪怕不完整)

  第2步: 候选生成器
     用组合/枚举/网络, 大量生成候选
     -> 不需要"好", 只需要"多"

  第3步: 验证器
     把第1步的条件实现成代码 (能跑、100%准)

  第4步: 迭代加严
     看筛出来的结果, 人给反馈"这个还不行, 因为X"
     -> 把 X 加进条件 -> 回到第3步

  ★ 关键: 第4步是【人机循环】, 每转一圈, 判定标准就更接近"品味"
  ★ 这就是 RLHF 的符号版本! (但不用训练权重, 只改规则)
""")
