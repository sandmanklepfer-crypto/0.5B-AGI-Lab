#!/usr/bin/env python3
"""海海因子压缩极限测试 — 300B级内容能否压到0.5B容量?
模拟: 海海因子生成的内容 (层1字因子→层2词因子→层3语义), 
测两种方案容量:
 A) 存因子库(全量): 需要多少参数?
 B) 存层间规则(有限): 需要多少参数? (0.5B走的路)
"""
import numpy as np

def main():
    # 模拟海海因子: 每层因子数是上层的~5倍 (我们实测中文: 821字→4253双字)
    # 词表规模参照真实: 字~3k, 词~50万, 语义概念~千万级
    layers = [
        ("字层", 3000),
        ("词层", 500000),
        ("短语层", 50000000),   # 5千万
        ("语义层", 1000000000), # 10亿 (接近300B模型的"内容覆盖")
    ]
    print("=== 海海因子: 全量存储 vs 规则存储 容量对比 ===")
    print(f"\n{'层级':<6}{'因子数':>14}{'存因子库(参数)':>18}{'存规则(参数)':>16}")
    total_store = 0
    total_rule = 0
    prev = 1
    for name, nf in layers:
        # A) 存因子库: 每因子~100维向量
        store = nf * 100
        # B) 存层间规则: 从上层因子组合出本层 (规则=稀疏组合, 每因子由~8个上层因子+权重)
        # 规则参数 ≈ 每本层因子 8个指针 + 8权重 (不用存向量)
        rule = nf * 16
        total_store += store
        total_rule += rule
        print(f"{name:<6}{nf:>14,}{store:>18,}{rule:>16,}")
        prev = nf
    print(f"\n总计-存因子库: {total_store/1e9:.2f} B参数")
    print(f"总计-存规则:   {total_rule/1e9:.3f} B参数")
    print(f"\n0.5B=5亿参数容量")
    print(f"存规则方案: {total_rule/5e8*100:.1f}% 的0.5B容量 (含全部层)")
    # 但规则还有"补齐机制"开销, 估算实际
    print(f"\n[结论] 若每层规则能复用(同一套组合机制), 容量可再降10-100倍")
    print(f"       → 0.5B装'分层规则+补齐机制' 理论可行")

if __name__ == '__main__':
    main()
