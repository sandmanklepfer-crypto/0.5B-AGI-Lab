# ============ 一、两者的「增长规律」完全不同 ============
print("【一】增长规律: 一条是幂律(慢), 一条是阶乘/指数(快)")
print()
E,A,al = 1.69, 406.4, 0.34
def capability(N): return A/(N**al)   # loss里的能力项, 越小越强
print(f"  {'参数':<10}{'能力项(越小越强)':<20}{'相对0.5B提升':<16}")
print("  "+"-"*56)
for N,nm in [(0.5e9,"0.5B"),(7e9,"7B"),(70e9,"70B"),(1e12,"1000B")]:
    c=capability(N)
    print(f"  {nm:<10}{c:<20.4f}{capability(0.5e9)/c:<16.2f}x")
print()
print("  ★ 参数从 0.5B 到 1000B (涨 2000 倍), 能力只涨 %.1f 倍"%(
      capability(0.5e9)/capability(1e12)))
print("  ★ 这就是「幂律」: 投入 2000 倍, 收获 %.1f 倍"%(capability(0.5e9)/capability(1e12)))
print()

# ============ 二、组合的增长 ============
