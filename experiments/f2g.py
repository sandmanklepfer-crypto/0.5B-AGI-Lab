W=20
print("\n【实验1】只有「组合」, 不能「命名」 -> 就是有限的")
print(f"  固定 {W} 个原子:")
print(f"  {'深度':<8}{'能表达的东西':<24}{'性质'}")
print("  "+"-"*52)
for d in [1,2,3,5,8]:
    print(f"  {d:<8}{W**d:<24.3e}有限")
print("  ★ 深度再大也是【有限】—— 这就是你说的那个坎")

print("\n【实验2】每层把组合结果【命名】成新原子")
atoms=W
print(f"  {'层':<6}{'可用原子数':<26}{'新增组合'}")
print("  "+"-"*58)
for d in range(1,5):
    combo=atoms*atoms
    atoms=atoms+combo
    print(f"  {d:<6}{atoms:<26.3e}{combo:.3e}")
print("  ★ 原子数【每层平方】-> 深度不再受限 -> 从有限跳到无限")

print("\n【实验3】一行定义换一层能力 (重复'上一层')")
