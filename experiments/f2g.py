print("  L2 重复L1 x次: x^x                输入3 ->", 3**3)
print("  L3 重复L2 x次: x^(x^x)            输入3 ->", 3**(3**3))
print("  L4 重复L3 x次: x^(x^(x^x))        输入3 -> 天文 (10^3.6e12)")
print("  ★ 每层只是【一行定义】, 能力却【指数跃迁】")
print("  ★ 而'重复上一层'这个动作本身就是【命名】")

print("\n【实验4】加知识 vs 加层级")
