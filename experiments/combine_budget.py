# ===== 三、能力 vs 参数 的幂律 =====
print("="*94)
print("三、能力随参数怎么涨? (幂律: 能力 ∝ 参数^0.34, Chinchilla)")
print("="*94)
print()
print(f"  {'模型':<12}{'参数':<14}{'相对能力':<14}{'MMLU估'}")
print("  "+"-"*56)
base=0.5e9
for nm,P,mmlu in [("0.5B",0.5e9,"~50%"),("1.5B",1.5e9,"~56%"),
                  ("7B",7e9,"~61%"),("13B",13e9,"~63%"),
                  ("70B",70e9,"~70%"),("1000B",1e12,"~78%")]:
    r=(P/base)**0.34
    print(f"  {nm:<12}{P/1e9:<14.1f}B{r:<14.2f}{mmlu}")
print()
print("  ★ 从 0.5B 到 1000B: 参数涨 2000 倍, 能力只涨 %.1f 倍"%((1e12/base)**0.34))
print("  ★ 这就是「涌现」的反面: 大部分能力提升要【巨大】参数换")
print()

