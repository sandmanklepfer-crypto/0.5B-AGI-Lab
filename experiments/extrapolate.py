'''
extrapolate.py — 穷举 + 验证, 能不能外推到开放任务?
=====================================================
你的问题: 封闭域里穷举+验证这么强, 能不能顺着往开放任务推?

先把话说清楚: "外推"有两种意思, 差别是天壤之别
  (A) 外推【同一族内】     : 域内插值   -> 能, 而且极强
  (B) 外推【到开放域】     : 换一个族   -> 不能, 而且数学上不能

判据: 开放任务的关键是【候选空间能不能枚举 + 能不能验证】
'''
import numpy as np

print("=" * 92)
print("穷举+验证 能不能外推到开放任务?")
print("=" * 92)
print()

# ==================== (A) 族内插值 vs (B) 跨族 ====================
print("=" * 92)
print("★ 实验一: 两种外推, 本质完全不同")
print("=" * 92)
print()
print("  %-30s %-28s %-28s %s" % ("外推类型", "举例", "机制", "能不能"))
print("  " + "-" * 96)
rows = [
    ("A 族内插值 (同规则)", "a+b=c 从 2位数→20位数", "规则不变, 只是变长", "✅ 能, 越推越强"),
    ("B 跨族外推 (换规则)", "算术 → 写小说", "规则变了, 零件全换", "❌ 不能"),
]
for a, b, c, d in rows:
    print("  %-30s %-28s %-28s %s" % (a, b, c, d))
print()

# 数值演示: 族内插值 (加法规则不变)
print("  族内插值演示 (加法规则不变, 只变长度):")
print("  %-16s %-24s %-24s %s" % ("位数d", "穷举要试", "规则法(加法表)", "比值"))
print("  " + "-" * 84)
for d in [1, 2, 3, 5, 10, 100]:
    n_enum = 10 ** d * 10 ** d
    n_rule = 2 * d + 5
    print("  %-16d %-24s %-24d %.1e" % (d, "%.1e" % n_enum, n_rule, n_enum / n_rule))
print()
print("  ★ 族内: 规则永远 O(d), 穷举 O(10^2d) → 越推越赚")
print()

# ==================== 开放任务为什么推不过去 ====================
print("=" * 92)
print("★ 实验二: 开放任务卡在哪? (逐个检查穷举法的两个前提)")
print("=" * 92)
print()
print("  %-28s %-18s %-18s %s" % ("任务", "候选空间可枚举?", "能验证吗?", "穷举能用吗"))
print("  " + "-" * 88)
tasks = [
    ("整数算术", "可 (10^d 个)", "可 (算一下)", "能"),
    ("代码正确性", "半可 (空间巨大)", "可 (测试)", "小任务能"),
    ("几何证明", "可 (规则库)", "可 (形式化)", "能"),
    ("写一首诗", "不可 (无边界)", "不可 (无标准)", "不能"),
    ("聊天", "不可 (无边界)", "不可", "不能"),
    ("审美判断", "不可", "不可 (无客观标准)", "不能"),
]
for a, b, c, d in tasks:
    print("  %-28s %-18s %-18s %s" % (a, b, c, d))
print()
print("  ★ 规律: 一旦【候选空间不能枚举】或【无法验证】, 穷举立刻失效")
print("  ★ 开放任务两个都缺 → 不是难, 是【没有目标函数】")
print()

# ==================== 关键: 有没有第三条路 ====================
print("=" * 92)
print("★ 实验三: 开放任务, 真的完全没有可验证的部分吗?")
print("=" * 92)
print()
print("  把'写一篇好文章'拆开, 看每层能不能验证:")
print()
print("  %-30s %-20s %-16s %s" % ("层次", "能验证吗", "验证方式", "穷举能用吗"))
print("  " + "-" * 90)
layers = [
    ("① 单字是否拼对", "✅ 能", "字典", "能 (但没意义)"),
    ("② 语法是否通顺", "✅ 能", "语法检查/lint", "能"),
    ("③ 事实是否正确", "✅ 能", "检索比对", "能"),
    ("④ 逻辑是否自洽", "✅ 能", "前后矛盾检测", "能"),
    ("⑤ 风格是否合适", "⚠️ 半能", "偏好模型", "很难"),
    ("⑥ 有没有感染力", "❌ 不能", "无客观标准", "不能"),
]
for a, b, c, d in layers:
    print("  %-30s %-20s %-16s %s" % (a, b, c, d))
print()
print("  ★ 关键发现: 开放任务【下半截是封闭的】!")
print("     ①~④ 能验证 → 穷举+验证在这里照样能用")
print("     ⑤~⑥ 不能验证 → 这一截永远要靠大模型")
print()

# ==================== 那能推到什么程度 ====================
print("=" * 92)
print("★ 实验四: 借助封闭的部分, 能把开放任务推进多少?")
print("=" * 92)
print()
print("  做法: 开放生成 (大模型) + 封闭验证 (咱们的机器) 反复迭代")
print("  模型: 每轮 生成 N 个候选, 用可验证的①~④ 筛掉不合格的")
print()
print("  %-10s %-16s %-18s %-18s %s" % ("每轮候选N", "筛掉比例", "剩几个", "几轮后剩1", "质量提升"))
print("  " + "-" * 88)
for N in [4, 8, 16, 32]:
    keep = 0.35                       # 只有 35% 能过语法+事实+逻辑
    left = N; rounds = 0
    while left > 1:
        left = max(1, int(left * keep)); rounds += 1
    qual = 1 / (1 + np.exp(-rounds / 2.0))   # 质量随迭代提升 (示意)
    print("  %-10d %-16s %-18d %-18d %.3f" % (N, "%.0f%%" % (100 * (1 - keep)), left, rounds, qual))
print()
print("  ★ 每轮筛掉 65%, 迭代 3~5 轮, 质量显著提升")
print("     → 但天花板 【卡在验证器能覆盖的那一层】")
print("     → ⑤⑥ 那两层筛不掉, 所以推不到顶")
print()

