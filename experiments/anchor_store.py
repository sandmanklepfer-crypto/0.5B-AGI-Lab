'''
anchor_store.py — 只存「锚点」, 靠运行时展开还原 —— 行不行?
=============================================================
你的想法:
  「量化到很低会崩, 但崩掉的锚点本身有意义.
    只存关键节点, 哪怕崩了不可读也没事,
    因为沿着节点能把完整信息推出来.」

决定成败的只有一个量: 【Lyapunov 指数 λ】(误差放大率)
  λ<0 收缩 -> 误差自己消失   ★ 锚点存再糙都能还原
  λ=0 中性 -> 误差不放大     ★ 存多少精度就保多少
  λ>0 混沌 -> 误差指数放大   ✗ 崩

用三个经典映射精确验证 (λ 是已知的精确值):
  收缩:  x → 0.5x + 0.3        λ = ln(0.5) = -0.693
  中性:  x → x + 0.3 (mod 1)   λ = 0
  混沌:  x → 4x(1-x)           λ = ln(2)   = +0.693
'''
import numpy as np, time

t0 = time.time()

MAPS = {
    "收缩  (λ=-0.693)": (lambda x: 0.5 * x + 0.3, -0.693),
    "中性  (λ= 0.000)": (lambda x: (x + 0.3) % 1.0, 0.0),
    "混沌  (λ=+0.693)": (lambda x: 4 * x * (1 - x), 0.693),
}
L = 60


def quant1(x, b):
    '''把 [0,1) 上的数存成 b 位'''
    lv = 2 ** b
    return np.floor(x * lv) / lv


print("=" * 94)
print("只存锚点、靠展开还原: 成不成, 只看 Lyapunov 指数 λ")
print("=" * 94)
print()

print("★ 实验一: 锚点存 8 位, 展开后误差怎么走?")
print()
print("   %-20s %-14s %-14s %-14s %s" % ("动力学", "锚点误差", "10步后", "40步后", "判定"))
print("   " + "-" * 84)
for nm, (f, lam) in MAPS.items():
    x0 = 0.41234
    TR = [x0]
    for _ in range(L):
        TR.append(f(TR[-1]))
    TR = np.array(TR)
    aq = quant1(TR[0], 8)
    e0 = abs(aq - TR[0])
    s = aq; es = {}
    for i in range(L):
        s = f(s)
        es[i + 1] = abs(s - TR[i + 1])
    tag = "✅ 误差自己消失" if es[40] < e0 else ("✅ 不放大" if es[40] < 0.05 else "❌ 崩")
    print("   %-20s %-14.2e %-14.2e %-14.2e %s" % (nm, e0, es[10], es[40], tag))
print()
print("   ★ 收缩: 8 位存完, 误差越放越小 -> 锚点粗糙无所谓")
print("   ★ 混沌: 8 位存完, 40 步后误差到 1e-1 -> 完全对不上")
print()

print("★ 实验二: 混沌系统 —— 锚点存 b 位, 能撑多少步?")
print()
print("   理论: 每步丢 1 位 (λ=ln2), 所以 b 位最多撑 b 步")
print()
f = MAPS["混沌  (λ=+0.693)"][0]
x0 = 0.41234
TR = [x0]
for _ in range(200):
    TR.append(f(TR[-1]))
TR = np.array(TR)
print("   %-10s %-18s %-18s %-22s %s" % ("存储位数b", "锚点误差", "撑到第几步", "实测/理论", "说明"))
print("   " + "-" * 88)
for b in [4, 8, 12, 16, 24]:
    aq = quant1(TR[0], b)
    e0 = abs(aq - TR[0])
    s = aq; steps = 0
    for i in range(200):
        s = f(s)
        if abs(s - TR[i + 1]) > 0.1:
            steps = i + 1
            break
    else:
        steps = 200
    print("   %-10d %-18.2e %-18d %-22s %s" % (b, e0, steps,
          "%d / %d" % (steps, b), "✅ 吻合理论" if abs(steps - b) <= 3 else "⚠️"))
print()
print("   ★ 每多存 1 位, 只多撑 1 步 —— 要撑 1000 步就得存 1000 位")
print("     这就是「量化到很低就崩」的精确原因")
print()

print("★ 实验三: 收缩系统 —— 锚点能存多稀疏、多久存一次?")
print()
f = MAPS["收缩  (λ=-0.693)"][0]
x0 = 0.41234
TR = [x0]
for _ in range(2000):
    TR.append(f(TR[-1]))
TR = np.array(TR)
print("   %-14s %-12s %-20s %s" % ("锚点间隔", "存几位", "还原最大误差", "判定"))
print("   " + "-" * 72)
for gap in [1, 5, 20, 100, 500]:
    errs = []
    for st in range(0, 2000 - gap, max(gap, 1)):
        aq = quant1(TR[st], 4)                  # ★ 只存 4 位
        s = aq
        for _ in range(gap):
            s = f(s)
        errs.append(abs(s - TR[st + gap]))
    print("   %-14d %-12d %-20.2e %s" % (gap, 4, np.mean(errs),
          "✅ 完美" if np.mean(errs) < 0.01 else "⚠️"))
print()
print("   ★ 收缩系统: 每 500 步存一次、只存 4 位, 依然能完美还原")
print("     -> 这才是你想要的「只存关键节点」")
print()

