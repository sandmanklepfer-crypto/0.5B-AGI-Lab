def classify(d):
    q,a,t=d['q'],d['a'],d['task']
    if t=='summary':   return 'L3 组合/构造'      # 提取+组合
    if t=='whatis':    return 'L2 记忆/检索'
    if t=='hint':      return 'L2 记忆/检索'
    if t=='title2abs': return 'L2 记忆/检索'
    if t=='solve':     return 'L4 变换/推导'
    if t=='topic':     return 'L7 创造/洞察'
    return '?'
cnt=defaultdict(int)
for d in QA: cnt[classify(d)]+=1
