'''zero5b_ceiling.py — 0.5B 的「极致智能」到底能不能追?'''
import time
t0 = time.time()

print("=" * 88)
print("一、先纠正: 7.3 秒/token 不是模型的速度, 是我实现的速度")
print("=" * 88)
print()
params = 0.5e9
flop_per_token = 2 * params          # 前向 = 2 x 参数量
t_meas = 7.3
eff = flop_per_token / t_meas
print(f"  0.5B 每次前向需要      {flop_per_token:.1e} FLOP")
print(f"  我实测 7.3 秒/token  ->  有效算力 {eff/1e9:.3f} GFLOPS")
print(f"  这颗 CPU (8核) 顶多能跑  ~10 GFLOPS")
print(f"  → 我只发挥了 {100*eff/1e10:.0f}%   (纯numpy, 没批处理, 没KV缓存, 全词表151936)")
print()
print(f"  {'实现方式':<34}{'预计速度':<18}{'相对现在'}")
print("  " + "-" * 74)
for nm, t in [("我这次的纯numpy实现", 7.3),
              ("加 KV 缓存 (只算新token)", 0.5),
              ("KV缓存 + 量化 + 优化BLAS", 0.15),
              ("CPU 上 llama.cpp (Q4)", 0.10),
              ("GPU 上跑 (真实部署)", 0.002)]:
    print(f"  {nm:<34}{f'{t*1000:.0f} ms/token':<18}{f'{7.3/t:.0f}x'}")
print()
print("  ★ 结论: 速度是【工程问题】, 不是 0.5B 的天花板")
print("     真实部署下 0.5B 是 2ms/token —— 比我这次快 3650 倍")
print()

print("=" * 88)
print("二、那「智能」呢? —— 0.5B 靠「多采样 + 验证」能到多高")
print("=" * 88)
print()
print("  关键公式: 采 N 次, 只要有一次对, 就算成功")
print("     成功率 = 1 - (1-p)^N")
print()
print(f"  {'单次成功率 p':<16}{'采10次':<12}{'采100次':<12}{'采1000次':<12}{'采10000次'}")
print("  " + "-" * 76)
for p in [0.01, 0.05, 0.10, 0.30, 0.50]:
    row = []
    for N in [10, 100, 1000, 10000]:
        row.append(1 - (1 - p) ** N)
    print(f"  {p:<16}{row[0]:<12.3f}{row[1]:<12.3f}{row[2]:<12.3f}{row[3]:.3f}")
print()
print("  ★ 关键: p=0.05 (很弱) 的模型, 采 100 次就能到 99.4%")
print("     这就是 o1 / R1 的核心机制 —— 不是模型变强, 是【多试+筛选】")
print()

print("=" * 88)
print("三、代价: 采 N 次要多久? (按优化后的 0.15 s/token 算)")
print("=" * 88)
print()
TOK = 50          # 一条推理链约 50 token
t_tok = 0.15
print(f"  {'采样数 N':<12}{'总 token':<14}{'耗时':<16}{'能到多少成功率(p=0.05)'}")
print("  " + "-" * 74)
for N in [1, 10, 100, 1000]:
    tot = N * TOK
    tt = tot * t_tok
    sr = 1 - (1 - 0.05) ** N
    print(f"  {N:<12}{tot:<14,}{f'{tt:.1f} s':<16}{sr:.4f}")
print()
print("  ★ 采 100 次 = 5000 token = 12.5 秒 -> 成功率 99.4%")
print("  ★ 对比: 大模型 1 次 = 50 token, 但可能要 30 秒 (70B) 且不保证对")
print()

print("=" * 88)
print("四、但有两条硬边界 (这两条绕不过)")
print("=" * 88)
print()
print("  边界1: 验证器必须【能排序】")
print("     · 数学/代码/逻辑 -> 能 (跑一下就知道对错)   ✅")
print("     · 写文章/审美   -> 不能 (没有标准答案)     ❌")
print()
print("  边界2: 采样必须【能覆盖正确答案】")
print("     · 如果 0.5B 根本想不到那个方向 (p≈0), 采多少次都是 0")
print("     · 这就是「泛化」的作用: 保证 p > 0")
print()
print(f"  {'场景':<34}{'p':<10}{'采100次成功率':<18}{'可行吗'}")
print("  " + "-" * 74)
for nm, p in [("0.5B 会做但常错 (有方向)", 0.05),
              ("0.5B 偶尔会做", 0.01),
              ("0.5B 完全不会 (无方向)", 0.0),
              ("0.5B 很擅长", 0.30)]:
    sr = 1 - (1 - p) ** 100
    print(f"  {nm:<34}{p:<10}{sr:<18.4f}{'✅ 可行' if sr > 0.9 else '❌ 不行'}")
print()
print("  ★ 所以分界线非常清楚:")
print("     0.5B 有【一点方向感】 -> 多采样能把它放大到接近 100%")
print("     0.5B 完全【没方向感】 -> 采多少次都是 0")
print()

print("=" * 88)
print("结论: 直接回答你")
print("=" * 88)
